const { chromium } = require('playwright');
const path = require('path');
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' }).catch(async () => chromium.launch());
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 } });
  const base = 'http://127.0.0.1:8123/index.html?mock';
  const errors = [];
  const mk = async (url, vp) => { const p = await ctx.newPage(); if (vp) await p.setViewportSize(vp); p.on('pageerror', (e) => errors.push(url + ': ' + e.message)); p.on('console', (m) => { if (m.type() === 'error') errors.push(url + ' console: ' + m.text()); }); await p.goto(url); return p; };
  const admin = await mk(base + '#admin', { width: 420, height: 860 });
  await admin.waitForSelector('#pin'); await admin.fill('#pin', '1234'); await admin.click('[data-act="pin"]');
  await admin.waitForSelector('[data-act="fill-demo"]'); await admin.click('[data-act="fill-demo"]'); await admin.waitForTimeout(300);
  await admin.click('[data-act="atab"][data-tab="rank"]'); await admin.waitForTimeout(200);
  const order = ['red','yellow','blue','purple'];
  for (const a of ['pool','kart','legs','water']) { const o = [...order].sort(() => Math.random()-0.5); for (let i=0;i<4;i++) await admin.selectOption(`select[data-rank="${a}"][data-pos="${i}"]`, o[i]); }
  await admin.click('[data-act="save-rank"]'); await admin.waitForTimeout(300);
  await admin.click('[data-act="atab"][data-tab="control"]'); await admin.waitForTimeout(200);
  await admin.screenshot({ path: 'tools/shots/admin.png' });
  const player = await mk(base, { width: 390, height: 844 });
  await player.waitForSelector('[data-act="join-team"]'); await player.screenshot({ path: 'tools/shots/p-join.png' });
  await player.click('[data-act="join-team"][data-team="red"]'); await player.waitForTimeout(200);
  await player.click('[data-act="join-name"] >> nth=0'); await player.waitForTimeout(400);
  await player.screenshot({ path: 'tools/shots/p-lobby.png', fullPage: true });
  const screen = await mk(base + '#screen');
  await screen.waitForTimeout(500); await screen.screenshot({ path: 'tools/shots/screen-lobby.png', fullPage: true });
  await admin.click('[data-act="draw"]'); await admin.waitForTimeout(400);
  await admin.click('[data-act="next-match"]'); await admin.waitForTimeout(800);
  await player.screenshot({ path: 'tools/shots/p-plan.png', fullPage: true });
  await screen.screenshot({ path: 'tools/shots/screen-plan.png' });
  const stageOf = async () => (await admin.evaluate(() => { const d = JSON.parse(localStorage.getItem('kkwar-mock-db')); return d.kkwar.match && d.kkwar.match.stage; }));
  const waitStage = async (stg, ms) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { if (await stageOf() === stg) return true; await admin.waitForTimeout(500); } throw new Error('stage ' + stg + ' not reached, at ' + await stageOf()); };
  for (let i = 0; i < 20; i++) { const b = await player.$('[data-act="tap"]'); if (b) await b.click(); }
  await admin.click('[data-act="advance"]');
  await waitStage('wave1', 5000); await admin.waitForTimeout(4000);
  await screen.screenshot({ path: 'tools/shots/screen-wave1.png' });
  await player.screenshot({ path: 'tools/shots/p-wave1.png', fullPage: true });
  await waitStage('pause1', 30000); await admin.waitForTimeout(800);
  await player.screenshot({ path: 'tools/shots/p-pause1.png', fullPage: true });
  await screen.screenshot({ path: 'tools/shots/screen-pause1.png' });
  const it = await player.$('[data-act="item"]'); if (it) await it.click();
  const pl = await player.$('[data-act="plan"][data-plan="back"]'); if (pl) await pl.click();
  await waitStage('wave2', 30000); await admin.waitForTimeout(5000);
  await screen.screenshot({ path: 'tools/shots/screen-wave2.png' });
  await waitStage('pause2', 30000);
  const it2 = await player.$('[data-act="item"]'); if (it2) await it2.click();
  await waitStage('wave3', 30000); await admin.waitForTimeout(8000);
  await screen.screenshot({ path: 'tools/shots/screen-wave3.png' });
  await waitStage('result', 60000); await admin.waitForTimeout(1500);
  await screen.screenshot({ path: 'tools/shots/screen-result.png', fullPage: true });
  await player.screenshot({ path: 'tools/shots/p-result.png', fullPage: true });
  await admin.screenshot({ path: 'tools/shots/admin-result.png', fullPage: true });
  const state = await admin.evaluate(() => JSON.parse(localStorage.getItem('kkwar-mock-db')));
  console.log('match stage', state.kkwar.match.stage, 'result', JSON.stringify(state.kkwar.match.result));
  console.log('errors:', errors.length ? errors.join('\n') : 'none');
  await browser.close();
})().catch((e) => { console.error('E2E FAIL', e); process.exit(1); });
